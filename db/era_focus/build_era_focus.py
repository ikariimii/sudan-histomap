"""Build db/era_focus.json (focus_bbox, zoom, flag_anchor per era) and db/city_layers/AUDIT.md.
Owner: Sudan Map Designer. Derived only from data/periods.json, db/extents/*.geojson, db/city_layers/cities.geojson.
Run: python3 db/era_focus/build_era_focus.py"""
import json, math, re, unicodedata, os
from shapely.geometry import shape
from shapely.ops import unary_union
try:
    from shapely.ops import polylabel
except ImportError:
    polylabel = None
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def slug(s):
    s = unicodedata.normalize('NFKD', s).encode('ascii', 'ignore').decode().lower()
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')
periods = json.load(open(f'{R}/data/periods.json'))['periods']
cities = json.load(open(f'{R}/db/city_layers/cities.geojson'))['features']
def bbox_of(geoms):
    b = unary_union(geoms).bounds; return list(b)
def pad(b, f=0.15, minspan=1.0):
    w, s, e, n = b; cx, cy = (w+e)/2, (s+n)/2
    dx = max(e-w, minspan)*(1+2*f)/2; dy = max(n-s, minspan)*(1+2*f)/2
    return [round(cx-dx, 3), round(cy-dy, 3), round(cx+dx, 3), round(cy+dy, 3)]
def zoom(b):
    span = max(b[2]-b[0], (b[3]-b[1])*1.3)
    return max(3, min(8, int(math.floor(math.log2(360/span)))))
out, audit = {}, []
for p in periods:
    sl = slug(p['name']); ex = json.load(open(f'{R}/db/extents/{sl}.geojson'))
    eg = [shape(f['geometry']) for f in ex.get('features', []) if f.get('geometry')]
    role_c = [c for c in cities if any(r.get('era_id') == sl for r in c['properties'].get('roles', []))]
    cg = [shape(c['geometry']) for c in role_c]
    fv = (json.load(open(f'{R}/data/eras/{sl}.json')).get('focus_view') if os.path.exists(f'{R}/data/eras/{sl}.json') else None)
    if not fv or not fv.get('bbox'):
        out[sl] = {'name': p['name'], 'stream': p['stream'], 'start': p['start'], 'end': p['end'], 'zoom': None,
                   'flag_anchor': None, 'flag_anchor_basis': None,
                   'null_reason': 'focus_view is null in data/eras (no cited extent features or city coordinates)',
                   'cities_with_role': sorted(c['properties']['id'] for c in role_c)}
        audit.append((sl, p, role_c)); continue
    fb = fv['bbox']
    polys = [g for g in eg if g.geom_type in ('Polygon', 'MultiPolygon')]
    if polys:
        u = unary_union(polys)
        big = max(u.geoms, key=lambda g: g.area) if u.geom_type == 'MultiPolygon' else u
        pt = polylabel(big, tolerance=0.01) if polylabel else big.representative_point()
        if not big.contains(pt): pt = big.representative_point()
        anchor, ab = [round(pt.x, 3), round(pt.y, 3)], 'polygon-pole'
    else:
        caps = [c for c in role_c if any(r.get('era_id') == sl and r.get('role') == 'capital' for r in c['properties']['roles'])]
        pts = [g for g in eg if g.geom_type == 'Point']
        if caps or role_c:
            c = (caps or role_c)[0]; anchor, ab = [round(x, 3) for x in c['geometry']['coordinates']], 'main-city:' + c['properties']['id']
        else:
            anchor, ab = [round(pts[0].x, 3), round(pts[0].y, 3)], 'extent-point'
    out[sl] = {'name': p['name'], 'stream': p['stream'], 'start': p['start'], 'end': p['end'],
               'zoom': zoom(fb), 'zoom_basis': 'derived from data/eras/<era>.json focus_view.bbox',
               'flag_anchor': anchor, 'flag_anchor_basis': ab, 'cities_with_role': sorted(c['properties']['id'] for c in role_c)}
    audit.append((sl, p, role_c))
meta = {'owner': 'Sudan Map Designer', 'script': 'db/era_focus/build_era_focus.py',
 'note': 'Canonical zoom box is data/eras/<era>.json focus_view (Historian). This file has no bbox; zoom is derived from focus_view.bbox, null when focus_view is null.',
 'zoom': 'floor(log2(360/max(width, height*1.3))) clamped 3-8',
 'flag_anchor': "[lon,lat] for the Historian's flags: polygon-pole = pole of inaccessibility of largest extent polygon (inside it); main-city:<id> = capital/role city; extent-point = first extent point; null with null_reason when focus_view is null"}
json.dump({'meta': meta, 'eras': out}, open(f'{R}/db/era_focus.json', 'w'), ensure_ascii=False, indent=1)
# Audit
WATCH = ['meroe','napata','kerma','old dongola','soba','sennar','suakin','el fasher','omdurman','khartoum','el obeid','kassala','juba','wau','malakal','port sudan','berber','shendi','faras','qasr ibrim','aksum','gondar','abeche','wad medani','bor','fashoda','rumbek','gondokoro']
byname = {}
for c in cities:
    pr = c['properties']; byname[pr['name_en'].lower()] = pr
L = ['# City layer audit (for Sudan Historian)', '', 'Generated by db/era_focus/build_era_focus.py. No cities added; gaps only. A city counts for an era if it has a cited `roles[].era_id` for it.', '',
     '## Eras with zero or one city carrying a role', '', '| era | stream | years | role cities |', '|---|---|---|---|']
for sl, p, rc in audit:
    if len(rc) <= 1: L.append(f"| {sl} | {p['stream']} | {p['start']}..{p['end']} | {', '.join(c['properties']['id'] for c in rc) or '—'} |")
L += ['', '## Recurring main cities: status in cities.geojson', '', '| city | status | visible_from..to | eras with role |', '|---|---|---|---|']
for w in WATCH:
    wid = {'wad medani': 'wad-madani', 'kodok': 'fashoda'}.get(w, w.replace(' ', '-'))
    pr = next((c['properties'] for c in cities if c['properties']['id'] == wid), None) or byname.get(w)
    if not pr: L.append(f'| {w} | MISSING from cities.geojson | | |'); continue
    eras = sorted({r.get('era_id') for r in pr.get('roles', [])})
    st = 'no roles' if not eras else 'ok'
    L.append(f"| {w} ({pr['id']}) | {st} | {pr.get('visible_from')}..{pr.get('visible_to')} | {', '.join(eras)} |")
L += ['', '## Dating checks', '', 'Role windows outside the city visible window, or outside the era bracket (per existing cites):', '']
per = {slug(p['name']): p for p in periods}; n = 0
for c in cities:
    pr = c['properties']; vf, vt = pr.get('visible_from'), pr.get('visible_to') or 2026
    for r in pr.get('roles', []):
        e = per.get(r.get('era_id')); rs, re_ = r.get('start'), r.get('end')
        msg = []
        if e is None: msg.append(f"era_id `{r.get('era_id')}` not in periods.json")
        if rs is not None and vf is not None and rs < vf: msg.append(f'role start {rs} < visible_from {vf}')
        if re_ is not None and re_ > vt: msg.append(f'role end {re_} > visible_to {vt}')
        if e and rs is not None and re_ is not None and (re_ < e['start'] or rs > e['end']): msg.append(f"role {rs}..{re_} outside era {e['start']}..{e['end']}")
        if msg: n += 1; L.append(f"- {pr['id']} / {r.get('era_id')}: " + '; '.join(msg) + f" (cite {r.get('source_id')} p.{r.get('page')})")
if not n: L.append('- none found')
L += ['', '## Notes for the Historian', '',
 '- Visible windows narrower than the city\'s known history (check against existing cites before widening): e.g. Kerma visible only -1730..-1580 although the era runs -2450..-1480; Napata ends -300 though Meroitic-era role exists; Old Dongola ends 1365.',
 '- Cities present but with no era role (so they never mark an era as theirs): see `no roles` rows above (e.g. Sennar has no role for funj-sultanate-of-sennar; El Obeid, Juba, Berber, Shendi none).',
 '- MISSING rows (e.g. Wau, Malakal, Abeche) need a cited record before they can be drawn. Nothing was added here.',
 '- All modern Republic-of-Sudan eras (1956-2026) and the Republic of South Sudan have zero role cities; Khartoum/Juba roles for them would need cites.']
open(f'{R}/db/city_layers/AUDIT.md', 'w').write('\n'.join(L) + '\n')
